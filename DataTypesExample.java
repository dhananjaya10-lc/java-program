public class DataTypesExample {
    public static void main(String[] args) {

        // Declaring variables of different data types
        int number = 100;
        float decimalNumber = 45.67f;
        double largeDecimal = 12345.6789;
        char letter = 'A';
        boolean isJavaFun = true;
        String message = "Hello Java";

        // Displaying values
        System.out.println("Integer value: " + number);
        System.out.println("Float value: " + decimalNumber);
        System.out.println("Double value: " + largeDecimal);
        System.out.println("Character value: " + letter);
        System.out.println("Boolean value: " + isJavaFun);
        System.out.println("String value: " + message);
    }
}